let kept = 0;
let removed = 0;
for (const category of raw.categories) {
  category.skills = category.skills.filter((skill) => {
    if (REMOVE.has(skill.code)) {
      removed += 1;
      return false;
    }
    kept += 1;
    if (RENAME[skill.code]) skill.name = RENAME[skill.code];
    return true;
  });
}

